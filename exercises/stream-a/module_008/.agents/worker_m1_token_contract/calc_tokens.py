def srgb_to_lin(c):
    c = c / 255.0
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4

def hex_to_lum(h):
    h = h.lstrip('#')
    r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
    return 0.2126 * srgb_to_lin(r) + 0.7152 * srgb_to_lin(g) + 0.0722 * srgb_to_lin(b)

result = {}
for pal, steps in palettes.items():
    result[pal] = {}
    for step, h in sorted(steps.items()):
        lum = hex_to_lum(h)
        result[pal][step] = {
            'hex': h.upper(),
            'relative_luminance': round(lum, 6)
        }

print(json.dumps(result, indent=2))
